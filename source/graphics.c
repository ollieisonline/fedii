// Draw a character
void draw_char(u8* fb, int x, int y, char c, u32 color, int screen_width) {
    if (c < 32 || c > 126) c = '?';
    
    int font_idx = c - 32;
    if (font_idx >= 96) font_idx = '?' - 32;
    
    for (int dy = 0; dy < 8; dy++) {
        u8 row = font_data[font_idx][dy];
        for (int dx = 0; dx < 6; dx++) {
            if (row & (1 << (5 - dx))) {
                int px = x + dx;
                int py = y + dy;
                if (px >= 0 && px < screen_width && py >= 0 && py < SCREEN_HEIGHT_TOP) {
                    u8* pixel = fb + (py * screen_width + px) * 3;
                    pixel[0] = (color >> 16) & 0xFF;
                    pixel[1] = (color >> 8) & 0xFF;
                    pixel[2] = color & 0xFF;
                }
            }
        }
    }
}

// Draw text with proper font
void draw_text(u8* fb, int x, int y, const char *text, u32 color, int screen_width) {
    int pos = 0;
    while (text[pos] && x + pos * 6 < screen_width) {
        draw_char(fb, x + pos * 6, y, text[pos], color, screen_width);
        pos++;
    }
}
